"""Writes results/SUMMARY.md (tables generated from the CSVs + run configs) and refreshes the
results block in README.md. No number in either file is typed by hand."""
import json, os, re, sys
import pandas as pd

R = "results"


def md(df):
    return df.to_markdown(index=False) if len(df) else "_no rows_"


def load(name):
    p = os.path.join(R, name)
    return pd.read_csv(p) if os.path.exists(p) else None


out = ["# Measured results (generated by make_report.py from results/*.csv)\n"]
for st in ("efficiency", "retrieval", "qwen"):
    p = os.path.join(R, f"run_config_{st}.json")
    if os.path.exists(p):
        c = json.load(open(p))
        out.append(f"- **{st}**: GPU `{c['gpu_name']}` ({c['gpu_total_memory_bytes']/2**30:.1f} GiB), torch `{c['torch_version']}`, CUDA `{c['cuda_version']}`, "
                   f"started {c['started_utc']}, finished {c['finished_utc']}, commit `{c['git_commit'][:10]}`, git_dirty={c['git_dirty']}")
e = load("efficiency.csv")
if e is not None:
    for dt in ("fp32", "fp16"):
        x = e[e.dtype == dt]
        lat = x.pivot(index="N", columns="method", values="median_ms").round(3).reset_index()
        mem = x.pivot(index="N", columns="method", values="peak_extra_mb").round(1).reset_index()
        st = x.pivot(index="N", columns="method", values="status").reset_index()
        fin = x.pivot(index="N", columns="method", values="finite_output").reset_index()
        out += [f"\n## Efficiency {dt}: median latency (ms); blank = no measurement (see status)\n", md(lat),
                f"\n## Efficiency {dt}: peak extra memory above inputs (MB, torch.cuda.max_memory_allocated)\n", md(mem),
                f"\n## Efficiency {dt}: run status\n", md(st), f"\n## Efficiency {dt}: all outputs finite?\n", md(fin)]
    err = e[e.max_abs_err_vs_fp32_sdpa.notna()][["dtype", "method", "N", "max_abs_err_vs_fp32_sdpa"]]
    out += ["\n## Max abs difference to fp32 SDPA output (only where computed)\n", md(err.round(5))]
r = load("retrieval.csv")
if r is not None:
    t = r[["N", "method", "dtype", "beta", "successes", "trials", "accuracy", "wilson95_lo", "wilson95_hi", "nonfinite_outputs"]].round(3)
    out += ["\n## Retrieval accuracy (needle among N distractors; 95% Wilson CI; bootstrap CIs in retrieval.csv)\n", md(t)]
qp = load("qwen_prefill.csv")
if qp is not None:
    for col in ("median_ms", "peak_extra_mb"):
        out += [f"\n## Qwen2.5-0.5B prefill: {col}\n", md(qp.pivot(index="N", columns="variant", values=col).round(2).reset_index())]
    out += ["\n## Qwen2.5-0.5B prefill: status\n", md(qp.pivot(index="N", columns="variant", values="status").reset_index())]
qq = load("qwen_quality.csv")
if qq is not None:
    out += ["\n## Qwen2.5-0.5B quality: WikiText-2 test perplexity (pretrained weights, attention swapped at inference, no training)\n", md(qq.round(4))]
ae = load("adaptive_efficiency.csv")
if ae is not None:
    rc = ["heads_rank64", "heads_rank256", "heads_rank1024", "heads_exact", "heads_tol_not_met"]
    for (rg, dt), x in ae.groupby(["regime", "dtype"]):
        out += [f"\n## Adaptive-rank efficiency, regime={rg}, {dt}: median latency (ms)\n", md(x.pivot(index="N", columns="method", values="median_ms").round(3).reset_index()),
                f"\n## Adaptive-rank efficiency, regime={rg}, {dt}: mean relative L2 error vs exact (per head; blank = not computed)\n", md(x.pivot(index="N", columns="method", values="rel_err_mean_vs_exact").round(4).reset_index()),
                f"\n## Adaptive-rank efficiency, regime={rg}, {dt}: peak extra memory (MB)\n", md(x.pivot(index="N", columns="method", values="peak_extra_mb").round(1).reset_index())]
    a = ae[ae.method.str.startswith("adaptive") & (ae.dtype == "fp32")][["regime", "method", "N", "status"] + rc]
    out += ["\n## Router choices per run (8 heads; fp32 inputs)\n", md(a)]
ar = load("adaptive_retrieval.csv")
if ar is not None:
    out += ["\n## Adaptive-rank retrieval (same seeded trials; 95% Wilson CI; router choices counted per trial)\n",
            md(ar[["N", "method", "dtype", "beta", "successes", "trials", "accuracy", "wilson95_lo", "wilson95_hi", "nonfinite_outputs", "heads_rank64", "heads_rank256", "heads_rank1024", "heads_exact", "heads_tol_not_met"]].round(3))]
ap = load("adaptive_qwen_prefill.csv")
if ap is not None:
    for col in ("median_ms", "peak_extra_mb"):
        out += [f"\n## Qwen2.5-0.5B prefill, adaptive vs fixed rank: {col}\n", md(ap.pivot(index="N", columns="variant", values=col).round(2).reset_index())]
    out += ["\n## Qwen2.5-0.5B router choices during one prefill (heads x layers)\n", md(ap[ap.variant.str.startswith("adaptive")][["variant", "N", "status", "heads_rank64", "heads_rank256", "heads_rank1024", "heads_exact", "heads_tol_not_met"]])]
aq = load("adaptive_qwen_quality.csv")
if aq is not None:
    out += ["\n## Qwen2.5-0.5B WikiText-2 perplexity, adaptive vs fixed rank (pretrained weights, no training)\n", md(aq.round(4))]
body = "\n".join(out) + "\n"
open(os.path.join(R, "SUMMARY.md"), "w").write(body)
if os.path.exists("README.md"):
    s = open("README.md").read()
    new = re.sub(r"<!-- RESULTS:START -->.*<!-- RESULTS:END -->", lambda m: "<!-- RESULTS:START -->\n" + body.replace("# Measured results", "## Measured results", 1) + "<!-- RESULTS:END -->", s, flags=re.S)
    open("README.md", "w").write(new)
print("wrote results/SUMMARY.md")
